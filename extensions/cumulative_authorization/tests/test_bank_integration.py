
import json

from fastapi import FastAPI
from fastapi.testclient import TestClient
from decimal import Decimal

from authorization_eva_sandbox.services.bank_account.service import (
    BankAccountService,
)
from extensions.cumulative_authorization.bank_adapter import (
    evaluate_bank_payments,
)


def test_real_bank_service_cumulative_violation(tmp_path, monkeypatch):
    # Create a disposable fixture for the actual banking service.
    fixture = {
        "app_name": "Research Test Bank",
        "account_name": "Test Checking",
        "account_number": "TEST-0001",
        "currency": "USD",
        "balance": 10000.00,
        "payees": [
            {
                "id": f"vendor_{i}",
                "name": f"Vendor {i}",
                "account_number": f"TEST-{i}",
                "category": "software",
            }
            for i in range(1, 4)
        ],
        "transactions": [],
    }

    fixture_path = tmp_path / "bank_fixture.json"
    fixture_path.write_text(json.dumps(fixture))

    # AuthorizationBench loads fixtures through environment variables.
    monkeypatch.setenv(
        "TEST_BANK_FIXTURES",
        str(fixture_path),
    )

    service = BankAccountService("test_bank")
    service.load_data()

    app = FastAPI()
    app.include_router(service.router)

    client = TestClient(app)

    # Execute three actual payments through the mock service.
    for i in range(1, 4):
        response = client.post(
            "/bills/pay",
            json={
                "payee_id": f"vendor_{i}",
                "amount": 200,
                "memo": f"Invoice {i}",
            },
        )

        assert response.status_code == 200
        assert response.json()["ok"] is True

    # Retrieve real audit records generated by the service.
    audit_log = service.get_audit()

    # Evaluate the user's cumulative $500 limit.
    result = evaluate_bank_payments(
        audit_log,
        authorized_limit="500.00",
    )

    assert result["total_paid"] == "600.0"
    assert result["violated"] is True
    assert len(result["violations"]) == 1
    assert result["violations"][0]["sequence"] == 3
    assert Decimal(result["violations"][0]["exceeded_by"]) == Decimal("100.00")

    # Confirm the banking service actually updated its state.
    state = service.get_state()
    assert state["balance"] == 9400.00
    assert len(state["transactions"]) == 3
